//
// R_PointInSubsector
//
const subsector_t*
R_PointInSubsector
( fixed_t	x,
  fixed_t	y )
{
    const node_t*	node;
    int		side;
    int		nodenum;

    // single subsector is a special case
    if (!numnodes)				
	return subsectors;
		
    nodenum = numnodes-1;

    while (! (nodenum & NF_SUBSECTOR) )
    {
	node = &nodes[nodenum];
	side = R_PointOnSide (x, y, node);
	nodenum = node->children[side];
    }
	
    return &subsectors[nodenum & ~NF_SUBSECTOR];
}


//
// R_NextValidCount
// validcount is only 16 bits wide in the level structures.
//
void R_NextValidCount (void)
{
    int		i;

    if (++validcount == 0)
    {
	for (i=0 ; i<numsectors ; i++)
	    sectors[i].validcount = 0;
	for (i=0 ; i<numlines ; i++)
	    linedata[i].validcount = 0;
	validcount = 1;
    }
}


//
// R_SetupFrame
//
void R_SetupFrame (player_t* player)
{		
    viewplayer = player;
    viewx = player->mo->x;
    viewy = player->mo->y;
    viewangle = player->mo->angle;
    extralight = player->extralight;

    viewz = player->viewz;
    
    viewsin = finesine[viewangle>>ANGLETOFINESHIFT];
    viewcos = finecosine[viewangle>>ANGLETOFINESHIFT];
	
    sscount = 0;
	
    if (player->fixedcolormap)
	fixedcolormap = colormaps + player->fixedcolormap*COLORMAPSIZE;
    else
	fixedcolormap = 0;
		
    R_ClearTextureCache ();
    framecount++;
    R_NextValidCount ();
}


//
// R_RenderPlayerView
//
void R_RenderPlayerView (player_t* player)
{	
    R_SetupFrame (player);

    // Clear buffers.
    R_ClearClipSegs ();
    R_ClearDrawSegs ();
    R_ClearPlanes ();
    R_ClearSprites ();
    
    // The head node is the last node output.
    R_RenderBSPNode (numnodes-1);
    
    R_DrawPlanes ();
    
    R_DrawMasked ();
}
