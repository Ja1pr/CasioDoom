{
    (void)detail;
    setsizeneeded = true;
    setblocks = blocks;
}


//
// R_ExecuteSetViewSize
//
void R_ExecuteSetViewSize (void)
{
    fixed_t	dy;
    int		i;

    setsizeneeded = false;

    // Two sizes only: with the status bar, or full screen.
    if (setblocks >= 11)
	viewheight = SCREENHEIGHT;
    else
	viewheight = SCREENHEIGHT - ST_HEIGHT;
    
    scaledviewwidth = viewwidth = SCREENWIDTH;

    centery = viewheight/2;
    centerx = viewwidth/2;
    centerxfrac = centerx<<FRACBITS;
    centeryfrac = centery<<FRACBITS;
    projection = centerxfrac;
    // Use fineangles/2 to get a lookup angle for each screen column
    clipangle = xtoviewangle[0];

    // psprite scales: weapons are still laid out for a 320 wide screen
    pspritescale = FRACUNIT*viewwidth/BASE_WIDTH;
    pspriteiscale = FRACUNIT*BASE_WIDTH/viewwidth;
    
    // thing clipping
    if (screenheightarray)
	for (i=0 ; i<viewwidth ; i++)
	    screenheightarray[i] = viewheight;
    
    // planes
    for (i=0 ; i<viewheight ; i++)
    {
	dy = ((i-viewheight/2)<<FRACBITS)+FRACUNIT/2;
	dy = abs(dy);
	yslope[i] = FixedDiv ( viewwidth/2*FRACUNIT, dy);
    }
}


