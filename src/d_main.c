//
// EVENT HANDLING
//
// Events are asynchronous inputs generally generated by the game user.
// Events can be discarded if no responder claims them
//
#define MAXEVENTS	16

static event_t	events[MAXEVENTS];
static int	eventhead;
static int	eventtail;

//
// D_PostEvent
// Called by the I/O functions when input is detected
//
void D_PostEvent (const event_t* ev)
{
    events[eventhead] = *ev;
    eventhead = (eventhead+1)&(MAXEVENTS-1);
}

//
// D_ProcessEvents
// Send all the events of the given timestamp down the responder chain
//
void D_ProcessEvents (void)
{
    event_t*	ev;
	
    for ( ; eventtail != eventhead ; eventtail = (eventtail+1)&(MAXEVENTS-1) )
    {
	ev = &events[eventtail];
	if (M_Responder (ev))
	    continue;               // menu ate the event
	G_Responder (ev);
    }
}


//
// D_Display
//  draw current display, possibly wiping it from the previous
//

// wipegamestate can be set to -1 to force a wipe on the next draw
gamestate_t     wipegamestate = GS_DEMOSCREEN;
extern  boolean setsizeneeded;
void R_ExecuteSetViewSize (void);

void D_Display (void)
{
    int				nowtime;
    int				tics;
    int				wipestart;
    boolean			done;
    boolean			wipe;

    // change the view size if needed
    if (setsizeneeded)
	R_ExecuteSetViewSize ();

    // save the current screen if about to wipe
    if (gamestate != wipegamestate)
	wipe = wipe_StartScreen ();
    else
	wipe = false;

    // do buffered drawing: the whole (tiny) screen is redrawn every frame
    switch (gamestate)
    {
      case GS_LEVEL:
	if (!gametic)
	    break;
	if (automapactive)
	    AM_Drawer ();
	else
	    R_RenderPlayerView (&players[displayplayer]);
	ST_Drawer ();
	HU_Drawer ();
	break;

      case GS_INTERMISSION:
	WI_Drawer ();
	break;

      case GS_FINALE:
	F_Drawer ();
	break;

      case GS_DEMOSCREEN:
	D_PageDrawer ();
	break;
    }
    
    // no damage/bonus flash outside of a level
    if (gamestate != GS_LEVEL)
	I_SetPalette (0);

    wipegamestate = gamestate;

    // draw pause pic
    if (paused)
	HU_DrawText ((SCREENWIDTH - 5*4)/2, 2, "PAUSE");

    // menus go directly to the screen
    M_Drawer ();          // menu is drawn even on top of everything
    NetUpdate ();         // send out any new accumulation

    // normal update
    if (!wipe)
    {
	I_FinishUpdate ();              // page flip or blit buffer
	return;
    }
    
    // wipe update
    wipe_EndScreen ();

    wipestart = I_GetTime () - 1;

    do
    {
	do
	{
	    nowtime = I_GetTime ();
	    tics = nowtime - wipestart;
	} while (!tics);
	wipestart = nowtime;
	done = wipe_ScreenWipe (tics);
    } while (!done);
}


//
//  D_DoomLoop
//
void D_DoomLoop (void)
{
    while (1)
    {
	// frame syncronous IO operations
	I_StartFrame ();                
	
	// process one or more tics
	TryRunTics (); // will run at least one tic

	// Update display, next frame, with current state.
	D_Display ();
    }
}


//
//  DEMO LOOP
//
static int	demosequence;
static int	pagetic;
static const char* pagename;


//
// D_PageTicker
// Handles timing for warped projection
//
void D_PageTicker (void)
{
    if (--pagetic < 0)
	D_AdvanceDemo ();
}


//
// D_PageDrawer
//
void D_PageDrawer (void)
{
    if (W_CheckNumForName (pagename) >= 0)
	V_DrawPatch (0,0, 0, W_CacheLumpName(pagename, PU_CACHE));
    else
	V_FillRect (0, 0, SCREENWIDTH, SCREENHEIGHT, V_WHITE);
}


//
// D_AdvanceDemo
// Called after each demo or intro demosequence finishes
//
void D_AdvanceDemo (void)
{
    advancedemo = true;
}

static void D_Page (const char* name, int tics)
{
    pagetic = tics;
    gamestate = GS_DEMOSCREEN;
    pagename = name;
}

// The converter keeps a demo only if its level is in the WAD.
static void D_Demo (const char* name)
{
    if (W_CheckNumForName (name) >= 0)
	G_DeferedPlayDemo (name);
    else
	D_Page ("TITLEPIC", 35*4);
}

//
// This cycles through the demo sequences.
// FIXME - version dependend demo numbers?
//
 void D_DoAdvanceDemo (void)
{
    players[consoleplayer].playerstate = PST_LIVE;  // not reborn
    advancedemo = false;
    usergame = false;               // no save / end game here
    paused = false;
    gameaction = ga_nothing;

    if ( gamemode == retail )
      demosequence = (demosequence+1)%7;
    else
      demosequence = (demosequence+1)%6;
    
    switch (demosequence)
    {
      case 0:
	D_Page ("TITLEPIC", gamemode == commercial ? 35 * 11 : 170);
	break;
      case 1:
	D_Demo ("DEMO1");
	break;
      case 2:
	D_Page ("CREDIT", 200);
	break;
      case 3:
	D_Demo ("DEMO2");
	break;
      case 4:
	D_Page ("HELP1", 200);
	break;
      case 5:
	D_Demo ("DEMO3");
	break;
        // THE DEFINITIVE DOOM Special Edition demo
      case 6:
	D_Demo ("DEMO4");
	break;
    }
}


//
// D_StartTitle
//
void D_StartTitle (void)
{
    gameaction = ga_nothing;
    demosequence = -1;
    D_AdvanceDemo ();
}


//
// D_DoomMain
//
void D_DoomMain (void)
{
    int			p;
    int			numfrags;
    const wadfrag_t*	frags;

    Z_Init ();
    frags = I_MapWad (&numfrags);
    W_Init (frags, numfrags);

    gamemode = (GameMode_t)cdinfo->gamemode;
    
    nomonsters = M_CheckParm ("-nomonsters");
    respawnparm = M_CheckParm ("-respawn");
    fastparm = M_CheckParm ("-fast");

    // get skill / episode / map from parms (PC test build only)
    startskill = sk_medium;
    startepisode = 1;
    startmap = 1;
    autostart = false;

    p = M_CheckParm ("-skill");
    if (p && p < myargc-1)
    {
	startskill = myargv[p+1][0]-'1';
	autostart = true;
    }

    p = M_CheckParm ("-warp");
    if (p && p < myargc-1)
    {
	if (gamemode == commercial)
	    startmap = atoi (myargv[p+1]);
	else if (p < myargc-2)
	{
	    startepisode = myargv[p+1][0]-'0';
	    startmap = myargv[p+2][0]-'0';
	}
	autostart = true;
    }
    
    // init subsystems
    V_Init ();
    M_LoadDefaults ();              // load before initing other systems
    M_Init ();
    R_Init ();
    P_Init ();
    I_Init ();
    D_CheckNetGame ();
    HU_Init ();
    ST_Init ();
    I_InitGraphics ();

    p = M_CheckParm ("-playdemo");
    if (p && p < myargc-1)
    {
	G_DeferedPlayDemo (myargv[p+1]);
	D_DoomLoop ();  // never returns
    }

    if (autostart)
	G_InitNew (startskill, startepisode, startmap);
    else
	D_StartTitle ();                // start up intro loop

    D_DoomLoop ();  // never returns
}
