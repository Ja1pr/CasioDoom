/*
 * gentables.c - generates src/r_viewtab.c for CasioDoom.
 *
 * The 3D view of the calculator port is always 128 pixels wide, so the
 * tables DOOM normally computes at start-up (R_InitTextureMapping,
 * R_InitLightTables, distscale) are constants and can live in ROM.
 *
 *   cc -o gentables tools/gentables.c src/tables.c src/m_fixed.c
 *   ./gentables > src/r_viewtab.c
 */
#include <stdio.h>
#include <stdlib.h>
#include "../src/doomdef.h"
#include "../src/tables.h"
#include "../src/m_fixed.h"

#define FIELDOFVIEW 2048
#define LIGHTSCALESHIFT 12
#define LIGHTZSHIFT 20
#define MAXLIGHTZ 128
#define DISTMAP 2

const fixed_t *finecosine = &finesine[FINEANGLES/4];
void I_Error (const char *e, ...) { (void)e; exit (1); }

int main (void)
{
    static int viewangletox[FINEANGLES/2];
    static angle_t xtoviewangle[SCREENWIDTH+1];
    int i, x, t, scale;
    int viewwidth = SCREENWIDTH;
    fixed_t centerxfrac = (viewwidth/2) << FRACBITS;
    fixed_t focallength = FixedDiv (centerxfrac,
				    finetangent[FINEANGLES/4+FIELDOFVIEW/2]);

    for (i=0 ; i<FINEANGLES/2 ; i++)
    {
	if (finetangent[i] > FRACUNIT*2)
	    t = -1;
	else if (finetangent[i] < -FRACUNIT*2)
	    t = viewwidth+1;
	else
	{
	    t = FixedMul (finetangent[i], focallength);
	    t = (centerxfrac - t+FRACUNIT-1)>>FRACBITS;
	    if (t < -1)
		t = -1;
	    else if (t>viewwidth+1)
		t = viewwidth+1;
	}
	viewangletox[i] = t;
    }
    for (x=0;x<=viewwidth;x++)
    {
	i = 0;
	while (viewangletox[i]>x)
	    i++;
	xtoviewangle[x] = (i<<ANGLETOFINESHIFT)-ANG90;
    }
    for (i=0 ; i<FINEANGLES/2 ; i++)
    {
	if (viewangletox[i] == -1)
	    viewangletox[i] = 0;
	else if (viewangletox[i] == viewwidth+1)
	    viewangletox[i]  = viewwidth;
    }

    printf ("// Generated by tools/gentables.c - do not edit.\n"
	    "// View mapping tables for a %d pixel wide view.\n\n"
	    "#include \"doomdef.h\"\n#include \"tables.h\"\n"
	    "#include \"m_fixed.h\"\n\n", viewwidth);

    printf ("const unsigned char viewangletox[FINEANGLES/2] =\n{");
    for (i=0 ; i<FINEANGLES/2 ; i++)
	printf ("%s%d,", (i%20) ? "" : "\n    ", viewangletox[i]);
    printf ("\n};\n\n");

    printf ("const angle_t xtoviewangle[SCREENWIDTH+1] =\n{");
    for (i=0 ; i<=viewwidth ; i++)
	printf ("%s0x%08x,", (i%6) ? "" : "\n    ", xtoviewangle[i]);
    printf ("\n};\n\n");

    printf ("const fixed_t distscale[SCREENWIDTH] =\n{");
    for (i=0 ; i<viewwidth ; i++)
    {
	fixed_t cosadj = abs(finecosine[xtoviewangle[i]>>ANGLETOFINESHIFT]);
	printf ("%s%d,", (i%8) ? "" : "\n    ", FixedDiv (FRACUNIT,cosadj));
    }
    printf ("\n};\n\n");

    // light diminishing by distance, as on the original 320 wide screen
    printf ("const unsigned char zlighttab[%d] =\n{", MAXLIGHTZ);
    for (i=0 ; i<MAXLIGHTZ ; i++)
    {
	scale = FixedDiv ((BASE_WIDTH/2*FRACUNIT), (i+1)<<LIGHTZSHIFT);
	scale >>= LIGHTSCALESHIFT;
	scale /= DISTMAP;
	if (scale > 255)
	    scale = 255;
	printf ("%s%d,", (i%16) ? "" : "\n    ", scale);
    }
    printf ("\n};\n");
    return 0;
}
